func TestInsights(t *testing.T) {
	sqlDB := testdb.Open(t, models.SkipFixtures, nil)
	t.Cleanup(func() {
		require.NoError(t, sqlDB.Close())
	})

	db := reform.NewDB(sqlDB, postgresql.Dialect, reform.NewPrintfLogger(t.Logf))
	q := db.Querier

	create := func(t *testing.T, cr *models.Insight) *models.Insight {
		t.Helper()
		require.NoError(t, models.CreateInsight(t.Context(), q, cr))
		return cr
	}

	t.Run("create and find", func(t *testing.T) {
		svc := "svc-find"
		labels := map[string]string{"k": "v"}
		cr := &models.Insight{
			CheckName:   "c1",
			Category:    "performance",
			Subcategory: "advisor",
			Interval:    models.Standard,
			ServiceID:   svc,
			ServiceName: "find-me",
			ServiceType: models.MySQLServiceType,
			NodeID:      "node-id",
			NodeName:    "node-find",
			Status:      models.CheckResultFailed,
			Summary:     "summary",
			Description: "description",
			Severity:    models.Severity(common.Error),
			CheckedAt:   models.Now(),
		}
		require.NoError(t, cr.SetLabels(labels))
		create(t, cr)
		require.NotEmpty(t, cr.ID) // generated by CreateInsight

		got, err := models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 1)
		assert.Equal(t, cr.ID, got[0].ID)
		assert.Equal(t, models.CheckResultFailed, got[0].Status)
		assert.Equal(t, models.Severity(common.Error), got[0].Severity)
		assert.Equal(t, "node-find", got[0].NodeName)

		gotLabels, err := got[0].GetLabels()
		require.NoError(t, err)
		assert.Equal(t, labels, gotLabels)
	})

	t.Run("filters", func(t *testing.T) {
		svc := "svc-filter"
		create(t, &models.Insight{
			CheckName: "weak_pwd", Category: "security", ServiceID: svc, ServiceName: "ProdMySQL",
			NodeName: "node-A", Status: models.CheckResultFailed, Summary: "s",
			Severity: models.Severity(common.Critical), CheckedAt: models.Now(),
		})
		create(t, &models.Insight{
			CheckName: "old_ver", Category: "configuration", ServiceID: svc, ServiceName: "devmysql",
			NodeName: "node-B", Status: models.CheckResultOK, Summary: "s",
			Severity: models.Severity(common.Info), CheckedAt: models.Now(),
		})

		// service_name: case-insensitive substring.
		got, err := models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, ServiceName: "prod"}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 1)
		assert.Equal(t, "ProdMySQL", got[0].ServiceName)

		// node_name: case-insensitive substring.
		got, err = models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, NodeName: "node-b"}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 1)
		assert.Equal(t, "node-B", got[0].NodeName)

		// category: exact.
		got, err = models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, Category: "security"}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 1)

		// check_name: exact.
		got, err = models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, CheckName: "old_ver"}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 1)

		// severity: exact.
		sev := models.Severity(common.Critical)
		got, err = models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, Severity: &sev}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 1)
		assert.Equal(t, models.Severity(common.Critical), got[0].Severity)

		// status.
		st := models.CheckResultOK
		got, err = models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, Status: &st}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 1)
		assert.Equal(t, models.CheckResultOK, got[0].Status)

		count, err := models.CountInsights(t.Context(), q, models.InsightFilters{ServiceID: svc})
		require.NoError(t, err)
		assert.Equal(t, 2, count)
	})

	t.Run("time range filter", func(t *testing.T) {
		svc := "svc-time"
		create(t, &models.Insight{
			CheckName: "c", ServiceID: svc, ServiceName: "s", NodeName: "n",
			Status: models.CheckResultFailed, Summary: "s",
			Severity: models.Severity(common.Warning), CheckedAt: models.Now().Add(-48 * time.Hour),
		})
		create(t, &models.Insight{
			CheckName: "c", ServiceID: svc, ServiceName: "s", NodeName: "n",
			Status: models.CheckResultFailed, Summary: "s",
			Severity: models.Severity(common.Warning), CheckedAt: models.Now(),
		})

		from := models.Now().Add(-24 * time.Hour)
		got, err := models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, From: &from}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 1)
	})

	t.Run("pagination ordered by checked_at desc", func(t *testing.T) {
		svc := "svc-page"
		base := models.Now()
		for i := range 5 {
			create(t, &models.Insight{
				CheckName: fmt.Sprintf("c%d", i), ServiceID: svc, ServiceName: "s", NodeName: "n",
				Status: models.CheckResultFailed, Summary: "s",
				Severity: models.Severity(common.Warning), CheckedAt: base.Add(time.Duration(i) * time.Minute),
			})
		}

		// First page, newest first.
		got, err := models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc}, 0, 2)
		require.NoError(t, err)
		require.Len(t, got, 2)
		assert.Equal(t, "c4", got[0].CheckName)
		assert.Equal(t, "c3", got[1].CheckName)

		// Last page holds the single oldest row.
		got, err = models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc}, 2, 2)
		require.NoError(t, err)
		require.Len(t, got, 1)
		assert.Equal(t, "c0", got[0].CheckName)

		count, err := models.CountInsights(t.Context(), q, models.InsightFilters{ServiceID: svc})
		require.NoError(t, err)
		assert.Equal(t, 5, count)
	})

	t.Run("mark read", func(t *testing.T) {
		svc := "svc-mark"
		cr1 := create(t, &models.Insight{
			CheckName: "c1", ServiceID: svc, ServiceName: "s", NodeName: "n",
			Status: models.CheckResultFailed, Summary: "s",
			Severity: models.Severity(common.Warning), CheckedAt: models.Now(),
		})
		cr2 := create(t, &models.Insight{
			CheckName: "c2", ServiceID: svc, ServiceName: "s", NodeName: "n",
			Status: models.CheckResultFailed, Summary: "s",
			Severity: models.Severity(common.Warning), CheckedAt: models.Now(),
		})

		require.NoError(t, models.MarkInsightsRead(t.Context(), q, []string{cr1.ID}, true))

		isRead := true
		got, err := models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, IsRead: &isRead}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 1)
		assert.Equal(t, cr1.ID, got[0].ID)

		notRead := false
		got, err = models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, IsRead: &notRead}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 1)
		assert.Equal(t, cr2.ID, got[0].ID)

		// Unmark.
		require.NoError(t, models.MarkInsightsRead(t.Context(), q, []string{cr1.ID}, false))
		got, err = models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, IsRead: &notRead}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 2)
	})

	t.Run("mark read by filters", func(t *testing.T) {
		svc := "svc-mark-filters"
		cr1 := create(t, &models.Insight{
			CheckName: "c1", Category: "security", ServiceID: svc, ServiceName: "s", NodeName: "n",
			Status: models.CheckResultFailed, Summary: "s",
			Severity: models.Severity(common.Warning), CheckedAt: models.Now(),
		})
		create(t, &models.Insight{
			CheckName: "c2", Category: "configuration", ServiceID: svc, ServiceName: "s", NodeName: "n",
			Status: models.CheckResultFailed, Summary: "s",
			Severity: models.Severity(common.Warning), CheckedAt: models.Now(),
		})

		// Only the matching row is updated.
		require.NoError(t, models.MarkInsightsReadByFilters(t.Context(), q, models.InsightFilters{ServiceID: svc, Category: "security"}, true))

		isRead := true
		got, err := models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, IsRead: &isRead}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 1)
		assert.Equal(t, cr1.ID, got[0].ID)

		// The read-state filter narrows the update to unread rows.
		notRead := false
		require.NoError(t, models.MarkInsightsReadByFilters(t.Context(), q, models.InsightFilters{ServiceID: svc, IsRead: &notRead}, true))
		got, err = models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, IsRead: &isRead}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 2)

		// Empty filters match every record.
		require.NoError(t, models.MarkInsightsReadByFilters(t.Context(), q, models.InsightFilters{}, false))
		got, err = models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc, IsRead: &isRead}, 0, 0)
		require.NoError(t, err)
		require.Empty(t, got)
	})

	t.Run("cleanup old results", func(t *testing.T) {
		svc := "svc-clean"
		create(t, &models.Insight{
			CheckName: "old", ServiceID: svc, ServiceName: "s", NodeName: "n",
			Status: models.CheckResultFailed, Summary: "s",
			Severity: models.Severity(common.Warning), CheckedAt: models.Now().Add(-72 * time.Hour),
		})
		create(t, &models.Insight{
			CheckName: "new", ServiceID: svc, ServiceName: "s", NodeName: "n",
			Status: models.CheckResultFailed, Summary: "s",
			Severity: models.Severity(common.Warning), CheckedAt: models.Now(),
		})

		require.NoError(t, models.CleanupOldInsights(t.Context(), q, models.Now().Add(-24*time.Hour)))

		got, err := models.FindInsights(t.Context(), q, models.InsightFilters{ServiceID: svc}, 0, 0)
		require.NoError(t, err)
		require.Len(t, got, 1)
		assert.Equal(t, "new", got[0].CheckName)
	})

	t.Run("filter values", func(t *testing.T) {
		// two results on the same service/node to prove deduplication
		for range 2 {
			create(t, &models.Insight{
				CheckName: "c", ServiceID: "svc-fv", ServiceName: "fv-svc-b", NodeName: "fv-node-b",
				Status: models.CheckResultFailed, Summary: "s",
				Severity: models.Severity(common.Warning), CheckedAt: models.Now(),
			})
		}
		create(t, &models.Insight{
			CheckName: "c", ServiceID: "svc-fv", ServiceName: "fv-svc-a", NodeName: "fv-node-a",
			Status: models.CheckResultOK, Summary: "s",
			Severity: models.Severity(common.Warning), CheckedAt: models.Now(),
		})

		serviceNames, nodeNames, err := models.FindInsightFilterValues(t.Context(), q)
		require.NoError(t, err)

		// other subtests insert their own rows, so assert on ours only
		assert.Equal(t, []string{"fv-svc-a", "fv-svc-b"}, filterByPrefix(serviceNames, "fv-svc-"))
		assert.Equal(t, []string{"fv-node-a", "fv-node-b"}, filterByPrefix(nodeNames, "fv-node-"))
	})
}

func filterByPrefix(values []string, prefix string) []string {
	var result []string
	for _, v := range values {
		if strings.HasPrefix(v, prefix) {
			result = append(result, v)
		}
	}
	return result
}
