// TestEncryptionRotation exercises the rotation flow without supervisord: the
// pmm-managed restart is simulated by reloading the default cipher and
// running the startup migration in-process.
func TestEncryptionRotation(t *testing.T) {
	keyPath := filepath.Join(t.TempDir(), "encryption.key")
	t.Setenv(encryption.CustomEncryptionKeyPathEnvVar, keyPath)
	require.NoError(t, os.WriteFile(keyPath, []byte(originalEncryptionKey), 0o600))

	db := testdb.Open(t, models.SkipFixtures, nil)
	t.Cleanup(func() {
		assert.NoError(t, db.Close())
	})
	q := reform.NewDB(db, postgresql.Dialect, nil).Querier

	provider := encryption.NewFileKeyProvider(keyPath)
	oldCipher, err := encryption.LoadCipher(provider)
	require.NoError(t, err)
	// make sure the process-wide cipher uses the original keyset even if
	// another test in this package initialized it first
	encryption.SetDefaultCipher(oldCipher)

	require.NoError(t, insertLegacyTestData(t.Context(), db))

	// legacy values must be detected as needing re-encryption
	ids, err := models.AgentsNeedingReencryption(q, oldCipher)
	require.NoError(t, err)
	require.Equal(t, []string{"1"}, ids)

	// rotate: add a new primary key; old values stay readable
	newKeyID, err := encryption.AddNewPrimaryKey(provider)
	require.NoError(t, err)
	require.NotEqual(t, oldCipher.PrimaryKeyID(), newKeyID)

	// "restart pmm-managed": reload the keyset and run the startup migration
	newCipher, err := encryption.LoadCipher(provider)
	require.NoError(t, err)
	require.Equal(t, newKeyID, newCipher.PrimaryKeyID())
	encryption.SetDefaultCipher(newCipher)
	require.NoError(t, models.MigrateEncryption(q))

	// the sweep converged: nothing references retired keys anymore
	require.NoError(t, waitForReencryption(q, newCipher))

	// stored values are envelopes carrying the new key ID and decrypt to the original secrets
	var storedUsername, storedPassword string
	err = db.QueryRowContext(t.Context(), `SELECT username, password FROM agents WHERE agent_id = $1`, "1").Scan(&storedUsername, &storedPassword)
	require.NoError(t, err)
	assert.NotEqual(t, originalUsernameHash, storedUsername)
	assert.NotEqual(t, originalPasswordHash, storedPassword)
	for _, stored := range []string{storedUsername, storedPassword} {
		keyID, ok := encryption.StoredKeyID(stored)
		require.True(t, ok)
		assert.Equal(t, newKeyID, keyID)
	}
	agent, err := models.FindAgentByID(q, "1")
	require.NoError(t, err)
	assert.Equal(t, "pmm-managed-username", agent.Username.Reveal())
	assert.Equal(t, "pmm-managed-password", agent.Password.Reveal())

	// prune the retired key; data remains readable
	retired, err := encryption.PruneRetiredKeys(provider)
	require.NoError(t, err)
	assert.Equal(t, []uint32{oldCipher.PrimaryKeyID()}, retired)

	prunedCipher, err := encryption.LoadCipher(provider)
	require.NoError(t, err)
	encryption.SetDefaultCipher(prunedCipher)
	agent, err = models.FindAgentByID(q, "1")
	require.NoError(t, err)
	assert.Equal(t, "pmm-managed-username", agent.Username.Reveal())

	// running the migration again is a no-op
	ids, err = models.AgentsNeedingReencryption(q, prunedCipher)
	require.NoError(t, err)
	assert.Empty(t, ids)
}

func insertLegacyTestData(ctx context.Context, db *sql.DB) error {
	now := time.Now()
	_, err := db.ExecContext(ctx,
		"INSERT INTO nodes (node_id, node_type, node_name, distro, node_model, az, address, created_at, updated_at) "+
			"VALUES ('1', 'generic', 'name', '', '', '', '', $1, $2)",
		now, now,
	)
	if err != nil {
		return err
	}

	_, err = db.ExecContext(ctx,
		`INSERT INTO agents (agent_id, agent_type, username, password, runs_on_node_id, pmm_agent_id, disabled, status, created_at, updated_at, tls, tls_skip_verify, qan_options, mysql_options, aws_options, exporter_options) `+
			`VALUES ('1', 'pmm-agent', $1, $2, '1', NULL, false, '', $3, $4, false, false, '{"max_query_length": 0, "query_examples_disabled": false, "comments_parsing_disabled": true, "max_query_log_size": 0}', '{"table_count_tablestats_group_limit": 0}', '{"rds_basic_metrics_disabled": true, "rds_enhanced_metrics_disabled": true}', '{"push_metrics": false, "expose_exporter": false}')`,
		originalUsernameHash, originalPasswordHash, now, now,
	)

	return err
}
