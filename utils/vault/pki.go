package vault

import (
	"context"
	"errors"
	"fmt"
	"net/http"
	"strings"
	"time"
)

// CertificateRequest is what a certificate is issued for, see IssueCertificate.
type CertificateRequest struct {
	CommonName string
	AltNames   []string
	IPSANs     []string
}

// Certificate is a certificate that a PKI secrets engine issued, with its private key and the
// certificate of the CA that issued it, in PEM format.
type Certificate struct {
	Certificate string
	PrivateKey  string
	IssuingCA   string
	Expiration  time.Time
}

// IssueCertificate issues a new certificate from a role of a PKI secrets engine, whose issue endpoint,
// <mount>/issue/<role>, path is. The private key is generated by Vault, and is not kept there.
// Nothing is cached: every call issues another certificate.
func (c *Client) IssueCertificate(ctx context.Context, path string, req CertificateRequest) (*Certificate, error) {
	path = strings.Trim(path, "/")
	body := map[string]string{"common_name": req.CommonName, "format": "pem"}
	if len(req.AltNames) != 0 {
		body["alt_names"] = strings.Join(req.AltNames, ",")
	}
	if len(req.IPSANs) != 0 {
		body["ip_sans"] = strings.Join(req.IPSANs, ",")
	}

	var resp struct {
		Data struct {
			Certificate string `json:"certificate"`
			PrivateKey  string `json:"private_key"`
			IssuingCA   string `json:"issuing_ca"`
			Expiration  int64  `json:"expiration"`
		} `json:"data"`
	}

	c.m.Lock()
	defer c.m.Unlock()

	err := c.withToken(ctx, func(token string) error {
		return c.do(ctx, http.MethodPost, path, token, body, &resp)
	})
	if err != nil {
		return nil, err
	}

	d := resp.Data
	if d.Certificate == "" || d.PrivateKey == "" || d.IssuingCA == "" {
		return nil, fmt.Errorf("vault %s: %w", path, errors.New("no certificate, private key, or issuing CA in the response"))
	}
	return &Certificate{
		Certificate: d.Certificate,
		PrivateKey:  d.PrivateKey,
		IssuingCA:   d.IssuingCA,
		Expiration:  time.Unix(d.Expiration, 0),
	}, nil
}
